function xmlEscape(value) {
  return String(value || '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

function titleFromMovieUrl(url) {
  try {
    const slug = decodeURIComponent(new URL(url).pathname.split('/').filter(Boolean).pop() || 'phim-moi');
    return slug.split('-').filter(Boolean).map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join(' ');
  } catch {
    return 'Phim mới trên KhoPhim';
  }
}

let recentMovieUrls = [];
try {
  const recentXml = await readFile(resolve('public/sitemap-movies-recent.xml'), 'utf8');
  recentMovieUrls = [...recentXml.matchAll(/<loc>(https:\/\/khophim\.org\/phim\/[^<]+)<\/loc>/g)]
    .map((match) => match[1])
    .slice(0, 50);
} catch {
  // The channel-only RSS below remains a valid last-resort document.
}
const buildDate = new Date().toUTCString();
const feedItems = recentMovieUrls.map((url) => `  <item>
    <title>${xmlEscape(titleFromMovieUrl(url))}</title>
    <link>${xmlEscape(url)}</link>
    <guid isPermaLink="true">${xmlEscape(url)}</guid>
    <pubDate>${xmlEscape(buildDate)}</pubDate>
  </item>`).join('\n');
const rssFallbackXml = `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0">
<channel>
  <title>KhoPhim - Phim mới cập nhật</title>
  <link>${SITE_URL}/</link>
  <description>Các trang phim chất lượng mới được KhoPhim cập nhật.</description>
  <language>vi-VN</language>
  <lastBuildDate>${xmlEscape(buildDate)}</lastBuildDate>
${feedItems}
</channel>
</rss>
`;
await writeFileWithRetry(resolve('public/feed.xml'), rssFallbackXml);
console.log(`Generated public/feed.xml fail-open fallback with ${recentMovieUrls.length} items.`);
