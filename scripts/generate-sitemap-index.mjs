import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { SITE_URL } from './seo-data.mjs';

const FALLBACK_MOVIE_CHUNKS = 18;

function today() {
  const parts = new Intl.DateTimeFormat('en', {
    timeZone: 'Asia/Ho_Chi_Minh',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).formatToParts(new Date());
  const get = (type) => parts.find((part) => part.type === type)?.value || '';
  return `${get('year')}-${get('month')}-${get('day')}`;
}

const sitemapFiles = [
  'sitemap-static.xml',
  'sitemap-seo-landing.xml',
  'sitemap-movies-recent.xml',
  'sitemap-movies-upcoming.xml',
  'sitemap-movies-ongoing.xml',
  'feed.xml',
];

const date = today();
const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-sitemap-index.mjs. Last updated: ${date} -->
<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${sitemapFiles.map((file) => `  <sitemap>
    <loc>${SITE_URL}/${file}</loc>
  </sitemap>`).join('\n')}
</sitemapindex>
`;

await writeFile(resolve('public/sitemap.xml'), xml, 'utf8');
console.log(`Generated public/sitemap.xml with ${sitemapFiles.length} child sitemaps.`);

const movieSitemapFiles = sitemapFiles.filter((file) =>
  file === 'sitemap-movies-recent.xml'
  || file === 'sitemap-movies-upcoming.xml'
  || file === 'sitemap-movies-ongoing.xml'
);
const movieXml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-sitemap-index.mjs. Last updated: ${date} -->
<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${movieSitemapFiles.map((file) => `  <sitemap>
    <loc>${SITE_URL}/${file}</loc>
  </sitemap>`).join('\n')}
</sitemapindex>
`;

await writeFile(resolve('public/sitemap-movies.xml'), movieXml, 'utf8');
console.log(`Generated public/sitemap-movies.xml with ${movieSitemapFiles.length} child sitemaps.`);

const archiveMovieSitemapFiles = Array.from(
  { length: FALLBACK_MOVIE_CHUNKS },
  (_, index) => `sitemap-movies-${index + 1}.xml`,
);
const archiveMovieXml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Archive movie sitemap index. Kept outside the recovery sitemap submitted to search engines. -->
<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${archiveMovieSitemapFiles.map((file) => `  <sitemap>
    <loc>${SITE_URL}/${file}</loc>
  </sitemap>`).join('\n')}
</sitemapindex>
`;

await writeFile(resolve('public/sitemap-movies-archive.xml'), archiveMovieXml, 'utf8');
console.log(`Generated public/sitemap-movies-archive.xml with ${archiveMovieSitemapFiles.length} archive chunks.`);
