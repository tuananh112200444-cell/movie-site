import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { SITE_URL } from './seo-data.mjs';

function today() {
  const parts = new Intl.DateTimeFormat('en', {
    timeZone: 'Asia/Ho_Chi_Minh',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).formatToParts(new Date());
  const get = (type) => parts.find((part) => part.type === type)?.value || '';
  return `${get('year')}-${get('month')}-${get('day')}`;
}

const currentDate = today();
const staticUrls = [
  { path: '/', lastmod: currentDate, changefreq: 'daily', priority: '1.0' },
  { path: '/vu-tru-dam-my', lastmod: currentDate, changefreq: 'daily', priority: '0.90' },
  { path: '/the-loai/hoat-hinh', lastmod: currentDate, changefreq: 'weekly', priority: '0.82' },
  { path: '/the-loai/lich-su', lastmod: currentDate, changefreq: 'weekly', priority: '0.76' },
  { path: '/press/', lastmod: '2026-07-19', changefreq: 'monthly', priority: '0.60' },
  { path: '/sitemap', lastmod: currentDate, changefreq: 'weekly', priority: '0.60' },
  { path: '/kho-phim', lastmod: currentDate, changefreq: 'daily', priority: '0.85' },
];

const entries = staticUrls.map((item) => `  <url>
    <loc>${SITE_URL}${item.path}</loc>
    <lastmod>${item.lastmod}</lastmod>
    <changefreq>${item.changefreq}</changefreq>
    <priority>${item.priority}</priority>
  </url>`).join('\n');

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-static-sitemap.mjs. Do not edit manually. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${entries}
</urlset>
`;

await writeFile(resolve('public/sitemap-static.xml'), xml, 'utf8');
console.log(`Generated public/sitemap-static.xml with ${staticUrls.length} non-landing URLs.`);
